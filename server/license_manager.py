from __future__ import annotations

import os
import sqlite3
import uuid
from datetime import datetime, timedelta
from pathlib import Path
from typing import Optional

DB_PATH = Path(__file__).resolve().parent.parent / "licenses.db"


def get_conn() -> sqlite3.Connection:
    conn = sqlite3.connect(str(DB_PATH), check_same_thread=False)
    conn.row_factory = sqlite3.Row
    return conn


def init_db() -> None:
    with get_conn() as conn:
        conn.execute(
            """
            CREATE TABLE IF NOT EXISTS licenses (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                customer_email TEXT NOT NULL,
                license_key TEXT NOT NULL UNIQUE,
                plan TEXT NOT NULL,
                created_at TEXT NOT NULL,
                expires_at TEXT,
                is_active INTEGER NOT NULL DEFAULT 1,
                notes TEXT
            )
            """
        )
        conn.commit()


def generate_license(customer_email: str, plan: str = "pro", days: int = 365) -> str:
    init_db()
    key = str(uuid.uuid4())
    expires_at = (datetime.utcnow() + timedelta(days=days)).isoformat()

    with get_conn() as conn:
        conn.execute(
            """
            INSERT INTO licenses (customer_email, license_key, plan, created_at, expires_at, is_active, notes)
            VALUES (?, ?, ?, ?, ?, 1, 'generated by ntumba IA')
            """,
            (customer_email, key, plan, datetime.utcnow().isoformat(), expires_at),
        )
        conn.commit()
    return key


def validate_license(license_key: str) -> Optional[dict]:
    init_db()
    with get_conn() as conn:
        row = conn.execute(
            "SELECT * FROM licenses WHERE license_key = ? AND is_active = 1 LIMIT 1",
            (license_key,),
        ).fetchone()

    if row is None:
        return None

    expires_at = row["expires_at"]
    if expires_at and datetime.fromisoformat(expires_at) < datetime.utcnow():
        return None

    return dict(row)


def deactivate_license(license_key: str) -> bool:
    with get_conn() as conn:
        cur = conn.execute(
            "UPDATE licenses SET is_active = 0 WHERE license_key = ?",
            (license_key,),
        )
        conn.commit()
        return cur.rowcount > 0
